def drugs_for_mkb_code(code: str) -> list[str]:
    """Вернуть типичные препараты по коду МКБ-10 (напр. 'A86', 'J06.9', 'K29')."""
    if not code:
        return []
    m = _MKB_CODE_RE.search(code.strip())
    if not m:
        return []
    letter = m.group(1).upper()
    # Кириллические коды МКБ отсутствуют, но на всякий случай нормализуем.
    try:
        num = int(m.group(2))
    except ValueError:
        return []
    for rule_letter, lo, hi, drugs in MKB_CHAPTER_DRUGS:
        if letter == rule_letter and lo <= num <= hi:
            return list(drugs)
    return []


def extract_mkb_code(text: str) -> str:
    """Достать код МКБ-10 из текста вида 'МКБ-10: A86. ...'."""
    if not text:
        return ""
    m = re.search(r"МКБ-?10[:\s]+([A-Z]\d{1,2}(?:\.\d+)?)", text, re.IGNORECASE)
    return m.group(1).upper() if m else ""

